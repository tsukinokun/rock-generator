//----------------------------------------------------------------------------
//! @file   ExportProfile.hpp
//! @brief  出力形式ごとの約束事
//! @detail 【Phase 0 の実測結果をコードに残したもの。推測で書き換えないこと】
//!
//!         書き出し本体（自前 GlbWriter / FbxExporter / PngWriter）は Phase 6 で
//!         実装します。ここには、形式ごとに何が違うかという測って分かった事実
//!         だけを先に置いてあります。
//!
//!         1. Assimp 5.0.1 のエクスポータは metallicRoughnessTexture と
//!            occlusionTexture を書き出さない。5枚渡しても3枚しか入らない。
//!            落としているのはインポータではなくエクスポータなので、
//!            エンジン側をどう直しても回収できない。
//!            → GLB は自前ライタが必須（Tools/make_test_glb.py が原型）
//!
//!         2. 自前で仕様どおりに書けば画像は5枚ともエンジンまで届く。
//!            落ちるのは参照の型名だけ:
//!              metallicRoughnessTexture → Assimp は UNKNOWN[0] へ入れる
//!                                          （エンジンは DIFFUSE_ROUGHNESS を見る）
//!              occlusionTexture         → Assimp は LIGHTMAP[0] へ入れる
//!                                          （エンジンは AMBIENT_OCCLUSION を見る）
//!            → エンジン側は ModelImporter.cpp:531,533 へフォールバックを
//!              2行足すだけで通る（Phase 6 で入れる）
//!
//!         3. GLB では UV の事前反転は不要。エンジンは全形式へ無条件に
//!            aiProcess_FlipUVs を掛けるが、glTF 経路では往復で相殺される。
//!            FBX 経路では V が反転するので事前に反転しておく必要がある。
//----------------------------------------------------------------------------
#pragma once
#include <RockCore/Types.hpp>

// 名前空間 RockExport
namespace RockExport {

    //------------------------------------------------------------------------
    //! @enum  ExportFormat
    //! 書き出す形式
    //------------------------------------------------------------------------
    enum class ExportFormat : RockCore::u8 {
        Glb = 0,    //!< エンジン向けの主経路。自前ライタで書く
        Fbx,        //!< 他の DCC との相互運用用。Assimp のエクスポータを使う
    };

    //------------------------------------------------------------------------
    //! @struct ExportProfile
    //! 形式ごとの約束事
    //------------------------------------------------------------------------
    struct ExportProfile {
        //! V を事前に反転して書くか。
        //!
        //! エンジンは読み込み時に全形式へ aiProcess_FlipUVs を掛ける。
        //! glTF 経路はそれが往復で相殺されるので反転不要、FBX 経路は
        //! 反転が残るので事前に反転しておく（Phase 0 で実測）。
        bool flipV = false;

        //! テクスチャをファイル内へ埋め込むか。
        //!
        //! 必ず true にする。エンジンのモデル埋め込み経路だけがミップ生成と
        //! BC3 圧縮、そして正しい sRGB / リニア判定を通る。外部 PNG 参照に
        //! すると単体テクスチャ経路へ落ち、法線・MR・AO が強制 sRGB で壊れる
        bool embedTextures = true;
    };

    //------------------------------------------------------------------------
    //! 形式に対応する約束事を返します。
    //! @param  [in] format 書き出す形式
    //! @return その形式のプロファイル
    //------------------------------------------------------------------------
    ExportProfile GetExportProfile(ExportFormat format);

}    // namespace RockExport
