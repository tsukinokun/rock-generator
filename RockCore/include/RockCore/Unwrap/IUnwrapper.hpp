//----------------------------------------------------------------------------
//! @file   IUnwrapper.hpp
//! @brief  UV 展開の差し替え口
//! @detail 八面体射影（速い・必ず単射）と xatlas（歪みが少ない）の 2 つを
//!         同じ口で扱います。ベイク側はどちらで展開されたかを知らなくても
//!         動くよう、インターフェースで切ってあります。
//!
//!         速さの差が桁で違う（八面体射影は 1ms 未満、xatlas は数百ms〜数秒）
//!         ため、この 2 つは「どちらが優れているか」ではなく役割が違います。
//!         スライダを掴んでいる間は八面体射影、離したら選ばれた方式で
//!         焼き直す、という使い分けを Pipeline が行います。
//----------------------------------------------------------------------------
#pragma once
#include <RockCore/Mesh/MeshBuilder.hpp>
#include <RockCore/Pipeline/CancelToken.hpp>

// 名前空間 RockCore
namespace RockCore {

    //------------------------------------------------------------------------
    //! @struct UnwrapSettings
    //! UV 展開の設定
    //------------------------------------------------------------------------
    struct UnwrapSettings {
        int textureSize = 1024;    //!< テクスチャの一辺。余白をテクセルで計算するのに使う
        int padding     = 4;       //!< チャート間の余白（テクセル）

        //--------------------------------------------------------------------
        //! テクセル密度（テクセル / メートル）。xatlas だけが見ます。
        //!
        //! 0 以下なら「テクスチャ 1 枚に収まる密度を xatlas に見積もらせる」
        //! 意味になります。こちらが既定で、単体の岩を 1 枚へ焼くツールでは
        //! ほぼ常にこれが正解です。明示した値がアトラス 1 枚に収まらないと
        //! 複数枚へ分割されてしまい、ベイクの出口が無くなります
        //--------------------------------------------------------------------
        float texelsPerUnit = 0.0f;
    };

    //------------------------------------------------------------------------
    //! @struct UnwrapStats
    //! UV 展開の結果を UI へ見せるための数値
    //------------------------------------------------------------------------
    struct UnwrapStats {
        const char* methodName = "";    //!< 実際に使われた展開器の名前

        u32   chartCount  = 0;       //!< チャート数。八面体射影では 0
        u32   vertexCount = 0;       //!< 展開後の頂点数（シームで複製された分を含む）
        float utilization = 0.0f;    //!< アトラスの占有率 [0,1]。八面体射影では 0

        //! ハードエッジ化で複製した頂点数。
        //! 展開の後段で分割するのでここに属する（RockMeshStats ではない）
        u32 splitVertexCount = 0;

        //! 要求された方式で展開できず、八面体射影へ落ちたか
        bool fellBack = false;

        //--------------------------------------------------------------------
        //! 落ちた理由。落ちていなければ nullptr。
        //!
        //! 静的な寿命を持つ文字列しか入れません（UI の写しへそのまま
        //! コピーされ、別スレッドから読まれるため）。訳さないのは、
        //! これが利用者向けの案内ではなく原因の切り分け用だから
        //--------------------------------------------------------------------
        const char* failureReason = nullptr;
    };

    //------------------------------------------------------------------------
    //! @class IUnwrapper
    //! UV 展開器の共通インターフェース
    //------------------------------------------------------------------------
    class IUnwrapper {
    public:
        virtual ~IUnwrapper() = default;

        //------------------------------------------------------------------
        //! メッシュへ UV を付けます。
        //!
        //! シームをまたぐ三角形があれば頂点を複製します。つまり
        //! positions / normals / indices も書き換わります。
        //!
        //! 同じメッシュへ二度呼んではいけません。一度展開したメッシュを
        //! もう一度渡すとシームの頂点が二重に複製されます。呼び出し側は
        //! 展開前のメッシュの写しから始めること（Pipeline がそうしています）。
        //!
        //! @param  [in,out] mesh     対象のメッシュ
        //! @param  [in]     settings 展開の設定
        //! @param  [in]     cancel   中断フラグ。nullptr でもよい
        //! @param  [out]    outStats 結果の数値。nullptr を渡してもよい
        //! @return 成功したら true
        //------------------------------------------------------------------
        virtual bool Unwrap(MeshBuilder&          mesh,
                            const UnwrapSettings& settings,
                            const CancelToken*    cancel,
                            UnwrapStats*          outStats) = 0;

        //! 表示用の名前を返します。
        //! @return 展開器の名前
        virtual const char* GetName() const = 0;
    };

}    // namespace RockCore
