//----------------------------------------------------------------------------
//! @file   RockPresets.hpp
//! @brief  岩の性格ごとのパラメータ一式
//! @detail つまみが増えると「それらしい組み合わせ」を毎回探すことになるので、
//!         代表的な4つを固定値として持ちます。
//!
//!         4つを繋いでいるのは主に edgeRounding（稜線の丸め）と
//!         planeCutCount（破断面の枚数）の2本で、角張った岩と丸い転石は
//!         この2本の両端です。
//----------------------------------------------------------------------------
#pragma once
#include <RockCore/Shape/RockParams.hpp>

// 名前空間 RockCore
namespace RockCore {

    //------------------------------------------------------------------------
    //! @enum  RockPreset
    //! 岩の性格
    //------------------------------------------------------------------------
    enum class RockPreset : u8 {
        Weathered = 0,    //!< 風化した露岩。破断面はあるが稜線がやや丸い
        Angular,          //!< 角張った岩。割れたての鋭い稜線と平らな面
        Boulder,          //!< 丸い転石。河原の石のように全体が丸い
        Slab,             //!< 板状の岩。上下に平らな面を持つ
        Count,
    };

    //! プリセットの総数
    constexpr u32 kRockPresetCount = static_cast<u32>(RockPreset::Count);

    //------------------------------------------------------------------------
    //! プリセットの識別子を返します。
    //!
    //! 英語の固定文字列です。UI の表示名は RockEditor 側で訳します
    //! （RockCore は UI を知らない）。
    //!
    //! @param  [in] preset プリセット
    //! @return 識別子
    //------------------------------------------------------------------------
    const char* GetRockPresetName(RockPreset preset);

    //------------------------------------------------------------------------
    //! プリセットのパラメータを作ります。
    //!
    //! @param  [in] preset プリセット
    //! @param  [in] seed   使うシード
    //! @return パラメータ一式
    //------------------------------------------------------------------------
    RockParams MakeRockPreset(RockPreset preset, u64 seed);

}    // namespace RockCore
