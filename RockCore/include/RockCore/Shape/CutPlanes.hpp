//----------------------------------------------------------------------------
//! @file   CutPlanes.hpp
//! @brief  岩の破断面を表す半空間の集合
//! @detail 岩が岩に見えるかどうかは、平らな破断面と稜線があるかでほぼ決まります。
//!         fBm だけでは等方で C1 連続な塊しか作れず、どれだけ振幅を上げても
//!         ジャガイモにしかなりません。
//!
//!         原点を内側に含む半空間 dot(p, n) <= d との交わりは星形を保つので、
//!         「vertex = center + dir * r(dir)」の不変条件を崩さずに入れられます。
//!         方向 dir のレイが平面を抜ける距離は d / dot(dir, n) です。
//----------------------------------------------------------------------------
#pragma once
#include <RockCore/Math/Vec.hpp>
#include <RockCore/Types.hpp>

#include <vector>

// 名前空間 RockCore
namespace RockCore {

    //------------------------------------------------------------------------
    //! @struct CutPlane
    //! 破断面 1 枚。半空間 dot(p, normal) <= distance の内側を残す
    //------------------------------------------------------------------------
    struct CutPlane {
        Vec3  normal{0.0f, 1.0f, 0.0f};    //!< 外向きの単位法線
        float distance = 1.0f;             //!< 原点から平面までの距離。必ず正
    };

    //------------------------------------------------------------------------
    //! @struct CutPlaneSettings
    //! 破断面の作り方
    //------------------------------------------------------------------------
    struct CutPlaneSettings {
        int   count    = 0;       //!< 枚数。0 なら丸い塊のまま
        float depth    = 0.25f;   //!< 中心へ食い込む深さの比率
        float axisBias = 0.0f;    //!< 法線を Y 軸へ寄せる度合い。1 に近いほど上下の面が主体
        float radius   = 0.5f;    //!< 外接球の半径
    };

    //------------------------------------------------------------------------
    //! 破断面を作ります。
    //!
    //! 同じ seed からは必ず同じ平面が出ます。平面用のサブシードは
    //! DeriveSeed で分けてあるので、ノイズ層のスライダを動かしても
    //! 破断面は変わりません。
    //!
    //! @param  [in] settings 平面の作り方
    //! @param  [in] seed     元のシード
    //! @return 破断面の列
    //------------------------------------------------------------------------
    std::vector<CutPlane> BuildCutPlanes(const CutPlaneSettings& settings, u64 seed);

}    // namespace RockCore
