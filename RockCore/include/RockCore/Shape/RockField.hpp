//----------------------------------------------------------------------------
//! @file   RockField.hpp
//! @brief  岩を星形（star-shaped）立体として定義する場
//! @detail 単位球上の方向 dir に対して半径 r(dir) を定め、表面を
//!         Mul(anisoScale, dir * r(dir)) で置きます。これを不変条件にすると
//!         下流がほぼ閉形式になります。
//!
//!         - ハイポリが要らない。ローポリのテクセル位置から r_full(dir) を
//!           1回評価すれば真の表面が出るので、hi→lo のレイキャストベイクが不要
//!         - AO のレイが安い。BVH ではなく1次元の符号変化探索で済む
//!         - メッシュが常に多様体・穴なし・自己交差なし。法線が解析的
//!
//!         代償はオーバーハング・洞窟・穴のある岩が作れないこと。
//!         単体の背景岩では無害と判断しています。
//----------------------------------------------------------------------------
#pragma once
#include <RockCore/Noise/NoiseStack.hpp>
#include <RockCore/Shape/CutPlanes.hpp>
#include <RockCore/Shape/RockParams.hpp>

#include <RockCore/Math/Vec.hpp>

#include <vector>

// 名前空間 RockCore
namespace RockCore {

    //------------------------------------------------------------------------
    //! @class RockField
    //! 岩の形を表す半径関数とその勾配
    //------------------------------------------------------------------------
    class RockField {
    public:
        //------------------------------------------------------------------
        //! 半径関数を構築します。
        //!
        //! 同じ params から maxFrequency 違いで2つ作る使い方を想定しています。
        //! メッシュ用（ナイキストで打ち切った r_low）とベイク用（全帯域の
        //! r_full）で、その差分が Normal マップへ焼かれます。
        //!
        //! @param [in] params       岩のパラメータ
        //! @param [in] maxFrequency 載せる周波数の上限。0 以下で無制限
        //------------------------------------------------------------------
        RockField(const RockParams& params, float maxFrequency);

        //------------------------------------------------------------------
        //! ノイズ抜きの半径を求めます。外接球と破断面だけを畳んだ値です。
        //!
        //! メッシュを細分割するときの射影先に使います。ノイズを含めると
        //! 中点が動いてしまい、破断面の平らさが保てません。
        //!
        //! @param  [in] dir 単位方向ベクトル
        //! @return 半径
        //------------------------------------------------------------------
        float BaseRadius(const Vec3& dir) const;

        //------------------------------------------------------------------
        //! 方向 dir の半径を求めます。異方スケールはここには含みません。
        //! @param  [in] dir 単位方向ベクトル
        //! @return 半径
        //------------------------------------------------------------------
        float Radius(const Vec3& dir) const;

        //------------------------------------------------------------------
        //! 方向 dir の表面上の点を求めます。異方スケールを含みます。
        //! @param  [in] dir 単位方向ベクトル
        //! @return 表面上の点
        //------------------------------------------------------------------
        Vec3 SurfacePoint(const Vec3& dir) const;

        //------------------------------------------------------------------
        //! 任意の位置から、その点が属する方向を求めます。
        //!
        //! 異方スケールを戻した空間での単位ベクトルです。ローポリ上の点から
        //! 「同じ方向にある真の表面」を引くのに使います。
        //!
        //! @param  [in] p 評価位置
        //! @return 単位方向ベクトル
        //------------------------------------------------------------------
        Vec3 DirectionOf(const Vec3& p) const;

        //------------------------------------------------------------------
        //! 任意の位置を、同じ方向の表面上へ射影します。
        //!
        //! ベイクの核心はこの1行です。ローポリのテクセル位置を全帯域の場へ
        //! 渡すだけで真の表面が出るため、hi→lo のレイキャストが要りません。
        //!
        //! @param  [in] p 射影したい位置
        //! @return 表面上の点
        //------------------------------------------------------------------
        Vec3 ProjectToSurface(const Vec3& p) const;

        //------------------------------------------------------------------
        //! 暗黙関数 F(p) の値を求めます。内側が負、表面が 0、外側が正です。
        //!
        //! 異方スケールを戻した空間で |q| - Radius(normalize(q)) を評価します。
        //! 表面でちょうど 0 になるので、AO のレイ（Phase 5）はこの符号変化を
        //! 1次元で探すだけで済みます。
        //!
        //! @param  [in] p 評価位置
        //! @return F(p)
        //------------------------------------------------------------------
        float Value(const Vec3& p) const;

        //------------------------------------------------------------------
        //! F の勾配を正4面体差分で求めます。外向きを指します。
        //!
        //! 中心差分（6回評価）ではなく4面体（4回評価）を使います。
        //! h はそのテクセルのワールドサイズに合わせること。そうすると
        //! ノイズが自動的にターゲット解像度へ帯域制限され、ミップの
        //! ちらつきが抑えられます。
        //!
        //! 符号について: F は内側が負・外側が正なので、勾配はそのまま
        //! 外向き法線の向きになります（反転させないこと）。
        //!
        //! @param  [in] p 評価位置
        //! @param  [in] h 差分幅（サンプル点までの距離）
        //! @return 勾配ベクトル（正規化はしていない）
        //------------------------------------------------------------------
        Vec3 Gradient(const Vec3& p, float h) const;

        //------------------------------------------------------------------
        //! 原点からの距離の上限を返します。カメラ配置とレイの開始点に使います。
        //! @return 岩が収まる球の半径
        //------------------------------------------------------------------
        float GetBoundingRadius() const { return m_boundingRadius; }

        // Phase 5 で足す:
        //   bool Raycast1D(const Vec3& origin, const Vec3& dir, float tMin, float tMax, float& outT) const;
        //   F(origin + dir*t) の符号変化を1次元探索する。BVH は要らない

        //------------------------------------------------------------------
        //! 破断面を返します。メッシュを同じ平面で切るのに使います。
        //! @return 破断面の列
        //------------------------------------------------------------------
        const std::vector<CutPlane>& GetCutPlanes() const { return m_cutPlanes; }

    private:
        NoiseStack            m_noise;
        std::vector<CutPlane> m_cutPlanes;

        float m_radius = 0.5f;
        Vec3  m_anisoScale{1.0f, 1.0f, 1.0f};
        Vec3  m_invAnisoScale{1.0f, 1.0f, 1.0f};
        float m_boundingRadius = 1.0f;

        //! 稜線を丸める幅（ワールド単位）。smooth min の k
        float m_edgeRounding = 0.0f;
    };

}    // namespace RockCore
