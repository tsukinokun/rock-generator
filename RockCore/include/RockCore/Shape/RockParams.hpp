//----------------------------------------------------------------------------
//! @file   RockParams.hpp
//! @brief  岩1個を決めるパラメータ一式
//! @detail これと seed だけで結果が決まります（RockCore はグローバル状態を
//!         持ちません）。Phase 3 以降で使うフィールドも最初から宣言してあるのは、
//!         後から足すと保存済み JSON の互換が壊れるためです。
//----------------------------------------------------------------------------
#pragma once
#include <RockCore/Noise/NoiseStack.hpp>

#include <RockCore/Math/Vec.hpp>
#include <RockCore/Types.hpp>

#include <vector>

// 名前空間 RockCore
namespace RockCore {

    //------------------------------------------------------------------------
    //! @enum  UnwrapMethod
    //! UV 展開の方式
    //------------------------------------------------------------------------
    enum class UnwrapMethod : u8 {
        Octahedral = 0,    //!< 八面体射影。星形保証があるので必ず単射。速い
        XAtlas,            //!< xatlas。チャートへ切って詰めるのでテクセル密度が揃う
    };

    //------------------------------------------------------------------------
    //! @struct RockParams
    //! 岩の形・見た目・ベイク設定をまとめたもの
    //------------------------------------------------------------------------
    struct RockParams {
        //--------------------------------------------------------------------
        // 基本
        //--------------------------------------------------------------------
        u64   seed   = 12345u;
        float radius = 0.5f;    // 半径の基準値（メートル）

        //! 軸ごとのスケール。(1, 0.25, 1) で板状の岩になる
        Vec3 anisoScale{1.0f, 1.0f, 1.0f};

        //--------------------------------------------------------------------
        // 形状
        //--------------------------------------------------------------------
        //! メッシュの目標エッジ長（メートル）。小さくすると三角形が増える
        float targetEdgeLength = 0.035f;

        //! 正二十面体の初期細分割回数。細分割の下限を決める
        int baseSubdivision = 2;

        //--------------------------------------------------------------------
        //! ノイズ層。既定は「風化した露岩」の3層。
        //!
        //!   1. 表面のうねりの fBm。
        //!      **振幅を破断面より大きくしないこと。** 形を作るのは破断面で、
        //!      fBm は面の上の揺らぎに徹する。ここを大きくすると平らな面が
        //!      波打って打ち消され、いくら平面で切ってもジャガイモに戻る
        //!   2. 割れ目の Worley。セル境界に沿って細い溝を彫る。
        //!
        //!      周波数の読み方に注意。ノイズは**単位球上**で評価するので、
        //!      サンプル点は半径 f の球に乗る。球面に入るセル数はおよそ
        //!      4*pi*f^2 で、f=4 なら 200 セルにもなって亀の甲羅になる。
        //!      岩全体に数本の割れを入れたいなら f は 1 前後。
        //!      溝を太くするとセルの間が膨らんでウロコになるので
        //!      sharpness も小さく保つ
        //!   3. 細かい fBm。周波数がメッシュのナイキストを超えるので頂点には
        //!      載らず、Normal マップだけに焼かれる（ローポリのままゴツゴツ光る）
        //!
        //! gain は 1/lacunarity（= 0.5）より小さくしてある。fBm の表面の傾きは
        //! おおよそ「振幅 × 周波数」の総和になるので、gain = 1/lacunarity だと
        //! 全オクターブが同じだけ傾きを足し、オクターブを増やすほど法線が寝ていく。
        //! 0.45 にすると高周波ほど寄与が減り、岩らしい「大きなうねり + 細かい粒」
        //! の比率になる
        //--------------------------------------------------------------------
        std::vector<NoiseLayerParams> noiseLayers{
            NoiseLayerParams{true, NoiseLayerKind::Fbm, 0.035f, 0.5f, FbmParams{1.3f, 4, 2.0f, 0.45f}},
            NoiseLayerParams{true, NoiseLayerKind::Worley, 0.014f, 0.07f, FbmParams{1.8f, 1, 2.0f, 0.5f}},
            NoiseLayerParams{true, NoiseLayerKind::Fbm, 0.016f, 0.5f, FbmParams{6.5f, 3, 2.0f, 0.45f}},
        };

        //--------------------------------------------------------------------
        // 破断面。
        //
        // ここが 0 だと fBm の丸い塊にしかならない。岩が岩に見えるかどうかは
        // 平らな面と稜線があるかでほぼ決まる
        //--------------------------------------------------------------------
        int   planeCutCount  = 8;       //!< 半空間クリップの枚数。0 で丸い転石に退化する
        float planeCutDepth  = 0.46f;   //!< 各平面が中心へ食い込む深さの比率
        float planeAxisBias  = 0.0f;    //!< 平面法線を Y 軸へ寄せる度合い。板状の岩で上げる

        //! 稜線の丸め（半径に対する比率）。smooth min の幅。
        //! 0 で割れたての鋭い角、大きくすると風化して角が落ちた形になる
        float edgeRounding = 0.09f;

        //! この角度を超えるエッジで頂点を分割してハードエッジにする
        float creaseAngleDeg = 35.0f;

        //--------------------------------------------------------------------
        // UV 展開。
        //
        // 既定は xatlas。八面体射影は必ず単射になる代わりに、正方形の対角へ
        // 向いた面だけテクセル密度が半分以下になり、Normal マップのディテールが
        // 面ごとに違って見える。破断面が入ると差がはっきり出る。
        //
        // 遅さ（数百ms〜数秒）は対話性には影響しない。スライダを掴んでいる間は
        // Pipeline が八面体射影へ落とし、離してから xatlas で焼き直す
        //--------------------------------------------------------------------
        UnwrapMethod unwrapMethod = UnwrapMethod::XAtlas;

        //! テクセル密度（テクセル / メートル）。xatlas だけが見る。
        //!
        //! 0 なら「テクスチャ 1 枚に収まる密度を xatlas に見積もらせる」意味で、
        //! 単体の岩を 1 枚へ焼くこのツールではこれが既定。明示した値が
        //! 1 枚に収まらないとアトラスが複数枚に割れ、焼き先が無くなる
        //! （そうなったら密度を縮めて詰め直すが、最後は八面体射影へ落ちる）
        float texelsPerUnit = 0.0f;

        int uvPadding = 4;    //!< チャート間の余白（テクセル）

        //--------------------------------------------------------------------
        // ベイク
        //--------------------------------------------------------------------
        //! テクスチャの一辺。エンジンが 2048 超を縮小し4の倍数へ丸めるため
        //! 512 / 1024 / 2048 しか選ばせない
        int textureSize = 1024;

        //! dilate（被覆マスクの膨張）のパス数
        int dilatePasses = 12;

        //! Normal ベイク時に使う全帯域の上限。0 以下で無制限
        float bakeMaxFrequency = 0.0f;

        //--------------------------------------------------------------------
        // マテリアル。
        //
        // ここは Albedo と MetallicRoughness へ焼かれます。単色の岩は
        // どれだけ形を作り込んでも粘土にしか見えないので、2 色の斑と
        // 窪みの汚れの 2 つを入れてあります。
        //--------------------------------------------------------------------
        Vec3 baseColor{0.46f, 0.44f, 0.42f};

        //! 斑のもう一方の色。基本色より暗い側に置くのが自然
        Vec3 secondaryColor{0.30f, 0.27f, 0.25f};

        //! 2 色の混ざり具合の強さ。0 で基本色の単色になる
        float colorVariation = 0.65f;

        //--------------------------------------------------------------------
        //! 斑の周波数（単位球上）。
        //!
        //! 形のノイズとは別のシードで評価します。同じノイズを使うと
        //! 「出っぱりが明るく窪みが暗い」だけになり、陰影と色が完全に
        //! 連動して作り物に見えます。実物の岩は鉱物の分布と凹凸が
        //! 一致しません。
        //!
        //! 周波数の読み方は形のノイズと同じで、単位球上のセル数は
        //! およそ 4*pi*f^2。岩全体に数個の斑が欲しいなら 2〜4 あたり
        //--------------------------------------------------------------------
        float colorNoiseFrequency = 3.0f;

        //! 窪みをどれだけ暗くするか。土や苔が溜まるので実物は必ず暗い
        float cavityDarkening = 0.70f;

        float roughness = 0.72f;

        //! 窪みでラフネスをどれだけ上げるか。汚れが溜まると艶が消える
        float cavityRoughness = 0.22f;

        float metallic = 0.0f;    //!< 岩なので常に 0。UI には出さない

        //--------------------------------------------------------------------
        // AO。
        //
        // このパイプラインで一番重い段です。テクセルごとに aoRayCount 本の
        // レイを撃ち、1 本あたり十数回 F を評価します。
        //--------------------------------------------------------------------
        int   aoRayCount = 48;
        float aoDistance = 0.15f;    //!< 遮蔽を探す距離（メートル）。0 で AO を切る

        //--------------------------------------------------------------------
        //! AO だけテクスチャの一辺を何分の 1 にするか。
        //!
        //! AO は低周波なので、他のマップと同じ解像度で焼く必要がありません。
        //! 1/4 にすればテクセル数が 1/16 になり、ベイク時間もそのまま 1/16 に
        //! なります。1024 のセットで AO だけ 256 になりますが、並べて比べても
        //! 違いが分かりません。
        //!
        //! エンジンも glTF もマップごとに大きさが違って構わないので、
        //! ここを落としても出口の作りは変わりません
        //--------------------------------------------------------------------
        int aoTextureDivisor = 4;
    };

}    // namespace RockCore
