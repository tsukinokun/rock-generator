//----------------------------------------------------------------------------
//! @file   RockParams.hpp
//! @brief  岩1個を決めるパラメータ一式
//! @detail これと seed だけで結果が決まります（RockCore はグローバル状態を
//!         持ちません）。Phase 3 以降で使うフィールドも最初から宣言してあるのは、
//!         後から足すと保存済み JSON の互換が壊れるためです。
//----------------------------------------------------------------------------
#pragma once
#include <RockCore/Noise/NoiseStack.hpp>

#include <RockCore/Math/Vec.hpp>
#include <RockCore/Types.hpp>

#include <vector>

// 名前空間 RockCore
namespace RockCore {

    //------------------------------------------------------------------------
    //! @enum  UnwrapMethod
    //! UV 展開の方式
    //------------------------------------------------------------------------
    enum class UnwrapMethod : u8 {
        Octahedral = 0,    //!< 八面体射影。星形保証があるので必ず単射。速い
        XAtlas,            //!< xatlas。歪みが少ない（Phase 3 で実装）
    };

    //------------------------------------------------------------------------
    //! @struct RockParams
    //! 岩の形・見た目・ベイク設定をまとめたもの
    //------------------------------------------------------------------------
    struct RockParams {
        //--------------------------------------------------------------------
        // 基本
        //--------------------------------------------------------------------
        u64   seed   = 12345u;
        float radius = 0.5f;    // 半径の基準値（メートル）

        //! 軸ごとのスケール。(1, 0.25, 1) で板状の岩になる
        Vec3 anisoScale{1.0f, 1.0f, 1.0f};

        //--------------------------------------------------------------------
        // 形状
        //--------------------------------------------------------------------
        //! メッシュの目標エッジ長（メートル）。小さくすると三角形が増える
        float targetEdgeLength = 0.035f;

        //! 正二十面体の初期細分割回数。細分割の下限を決める
        int baseSubdivision = 2;

        //--------------------------------------------------------------------
        //! ノイズ層。
        //!
        //! 既定は2層にしてある。1層目は塊感で、メッシュの頂点に載る。
        //! 2層目は周波数がメッシュのナイキストを超えるので頂点には載らず、
        //! Normal マップだけに焼かれる（＝ローポリのままゴツゴツ光る）。
        //! この2層の対比が、そのまま Phase 2 の狙いの実演になっている。
        //!
        //! gain は 1/lacunarity（= 0.5）より小さくしてある。fBm の表面の傾きは
        //! おおよそ「振幅 × 周波数」の総和になるので、gain = 1/lacunarity だと
        //! 全オクターブが同じだけ傾きを足し、オクターブを増やすほど
        //! 法線が寝ていく。0.45 にすると高周波ほど寄与が減り、岩らしい
        //! 「大きなうねり + 細かい粒」の比率になる
        //--------------------------------------------------------------------
        std::vector<NoiseLayerParams> noiseLayers{
            NoiseLayerParams{true, NoiseLayerKind::Fbm, 0.160f, FbmParams{1.4f, 4, 2.0f, 0.45f}},
            NoiseLayerParams{true, NoiseLayerKind::Fbm, 0.015f, FbmParams{6.5f, 3, 2.0f, 0.45f}},
        };

        //--------------------------------------------------------------------
        // Phase 3 で使う（今は宣言だけ）
        //--------------------------------------------------------------------
        int   planeCutCount = 0;       //!< 半空間クリップの枚数。0 で丸い転石に退化する
        float planeCutDepth = 0.25f;   //!< 各平面が中心へ食い込む深さの比率
        float creaseAngleDeg = 35.0f;  //!< この角度を超えるエッジで頂点分割しハードエッジにする

        //--------------------------------------------------------------------
        // UV 展開
        //--------------------------------------------------------------------
        UnwrapMethod unwrapMethod = UnwrapMethod::Octahedral;
        float        texelsPerUnit = 2048.0f;    //!< テクセル密度（Phase 3 の xatlas 用）
        int          uvPadding     = 4;          //!< チャート間の余白（テクセル）

        //--------------------------------------------------------------------
        // ベイク
        //--------------------------------------------------------------------
        //! テクスチャの一辺。エンジンが 2048 超を縮小し4の倍数へ丸めるため
        //! 512 / 1024 / 2048 しか選ばせない
        int textureSize = 1024;

        //! dilate（被覆マスクの膨張）のパス数
        int dilatePasses = 12;

        //! Normal ベイク時に使う全帯域の上限。0 以下で無制限
        float bakeMaxFrequency = 0.0f;

        //--------------------------------------------------------------------
        // マテリアル（Phase 4 で本格化。Phase 1 はプレビューの単色に使う）
        //--------------------------------------------------------------------
        Vec3  baseColor{0.46f, 0.44f, 0.42f};
        float roughness = 0.72f;
        float metallic  = 0.0f;    //!< 岩なので常に 0。UI には出さない

        //--------------------------------------------------------------------
        // AO（Phase 5）
        //--------------------------------------------------------------------
        int   aoRayCount = 48;
        float aoDistance = 0.15f;
    };

}    // namespace RockCore
