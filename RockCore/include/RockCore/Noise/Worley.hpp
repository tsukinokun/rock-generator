//----------------------------------------------------------------------------
//! @file   Worley.hpp
//! @brief  Worley（セルラー）ノイズによる割れ・欠け
//! @detail 岩が岩に見える最大の要因です。fBm は凹凸が対称なので「削れた跡」に
//!         ならないのに対し、Worley のセル境界は細い溝になります。
//!
//!         セル境界では F1（最近傍までの距離）と F2（2番目）が近づくので、
//!         F2 - F1 は境界で 0 へ落ちます。これを 1 から引けば境界だけが
//!         立ち上がるマスクになり、半径から引くと溝が彫れます。
//----------------------------------------------------------------------------
#pragma once
#include <RockCore/Math/Vec.hpp>
#include <RockCore/Types.hpp>

// 名前空間 RockCore
namespace RockCore {

    //------------------------------------------------------------------------
    //! @class Worley
    //! シード付きの 3D セルラーノイズ
    //------------------------------------------------------------------------
    class Worley {
    public:
        //------------------------------------------------------------------
        //! セルの大きさと溝の幅を決めます。
        //!
        //! @param [in] seed      シード
        //! @param [in] frequency セルの密度。大きいほど細かく割れる
        //! @param [in] width     溝の幅。0 に近いほど細く鋭い割れ目になる
        //------------------------------------------------------------------
        Worley(u64 seed, float frequency, float width);

        //------------------------------------------------------------------
        //! 割れ目のマスクを求めます。
        //!
        //! @param  [in] p 評価位置
        //! @return 0（平坦）〜 1（割れ目の底）
        //------------------------------------------------------------------
        float SampleCrack(const Vec3& p) const;

    private:
        //------------------------------------------------------------------
        //! セルの特徴点を求めます。
        //! @param  [in] cellX セルの X 番号
        //! @param  [in] cellY セルの Y 番号
        //! @param  [in] cellZ セルの Z 番号
        //! @return セル内の特徴点（セル座標系のオフセット 0〜1）
        //------------------------------------------------------------------
        Vec3 FeaturePoint(int cellX, int cellY, int cellZ) const;

        u64   m_seed      = 0;
        float m_frequency = 1.0f;
        float m_invWidth  = 1.0f;
    };

}    // namespace RockCore
