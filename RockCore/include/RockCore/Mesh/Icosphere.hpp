//----------------------------------------------------------------------------
//! @file   Icosphere.hpp
//! @brief  正二十面体を細分割した単位球メッシュ
//! @detail 緯度経度の球ではなく正二十面体を使うのは、極の縮退と継ぎ目が
//!         出ないためです。三角形の大きさもほぼ均一になるので、
//!         テクセル密度が暴れません。
//----------------------------------------------------------------------------
#pragma once
#include <RockCore/Mesh/MeshBuilder.hpp>

// 名前空間 RockCore
namespace RockCore {

    //------------------------------------------------------------------------
    //! 単位球の正二十面体メッシュを作ります。
    //!
    //! 頂点はすべて原点から距離 1 にあり、normals と uvs は空です
    //! （形へ射影してから作り直すため）。
    //!
    //! @param [out] outMesh      書き込み先。中身は上書きされる
    //! @param [in]  subdivisions 細分割回数。0 で素の正二十面体（20三角形）
    //------------------------------------------------------------------------
    void BuildIcosphere(MeshBuilder& outMesh, int subdivisions);

    //------------------------------------------------------------------------
    //! 目標エッジ長を満たす細分割回数を見積もります。
    //!
    //! 正二十面体の辺長は単位球で約 1.0515 で、1回の細分割でほぼ半分に
    //! なります。先に回数を決めておくと、細分割のたびに最長エッジを
    //! 測り直すより安く済みます。
    //!
    //! @param  [in] targetEdgeLength 目標のエッジ長
    //! @param  [in] sphereRadius     射影先の代表半径
    //! @param  [in] maxSubdivisions  返す値の上限
    //! @return 必要な細分割回数
    //------------------------------------------------------------------------
    int EstimateIcosphereSubdivisions(float targetEdgeLength, float sphereRadius, int maxSubdivisions);

}    // namespace RockCore
