//----------------------------------------------------------------------------
//! @file   HardEdgeSplit.hpp
//! @brief  クリース角を超えるエッジで頂点を分割する
//! @detail 破断面の稜線を「折れて見える」ようにするためのものです。
//!         法線を頂点で共有したままだと、平らな面どうしの境目が滑らかに
//!         補間されて丸まってしまい、せっかく切った意味がなくなります。
//!
//!         丸い部分の法線は触りません。そこは解析勾配（半径関数の勾配）の
//!         ほうが低いテッセレーションでも滑らかで、面法線の平均に置き換えると
//!         かえってカクつきます。稜線に乗っている頂点だけを複製します。
//----------------------------------------------------------------------------
#pragma once
#include <RockCore/Mesh/MeshBuilder.hpp>

// 名前空間 RockCore
namespace RockCore {

    //------------------------------------------------------------------------
    //! クリース角を超えるエッジで頂点を分割し、その頂点の法線を張り直します。
    //!
    //! mesh は normals を持っていること（解析勾配で埋めた状態を想定）。
    //!
    //! uvs があれば複製元と同じ値を引き継ぎます。**UV 展開より後に呼ぶこと。**
    //! 先に分割すると稜線の両側が別頂点になって法線シームが生まれ、xatlas が
    //! そこでチャートを切るため、面の数だけチャートが増えて詰め込みが崩れます。
    //! 展開を先にすれば、この関数は「位置と UV が同じで法線だけ違う頂点」を
    //! 足すだけになり、UV アトラスには一切触れません。
    //!
    //! @param  [in,out] mesh           対象のメッシュ
    //! @param  [in]     creaseAngleDeg この角度を超える隣接面の境目を稜線とみなす
    //! @return 複製した頂点の数
    //------------------------------------------------------------------------
    u32 SplitHardEdges(MeshBuilder& mesh, float creaseAngleDeg);

}    // namespace RockCore
