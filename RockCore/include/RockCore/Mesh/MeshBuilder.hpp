//----------------------------------------------------------------------------
//! @file   MeshBuilder.hpp
//! @brief  編集しやすい形の三角形メッシュ
//! @detail エンジンの MeshData（生バイト列 + VertexFormat）とは別物です。
//!         RockCore を GraphicsCommon から切り離しておくために自前の表現を
//!         持ち、GPU 向けへの詰め替えは RockEditor 側で行います。
//!
//!         頂点属性は position / normal / uv0 だけです。エンジンの .tsm が
//!         それしか持たないため（頂点カラーも接線も複数UVも非対応）、
//!         ここで余計に持っても出口がありません。
//----------------------------------------------------------------------------
#pragma once
#include <RockCore/Math/Vec.hpp>
#include <RockCore/Types.hpp>

#include <vector>

// 名前空間 RockCore
namespace RockCore {

    //------------------------------------------------------------------------
    //! @struct MeshBuilder
    //! 三角形メッシュの中間表現
    //------------------------------------------------------------------------
    struct MeshBuilder {
        std::vector<Vec3> positions;
        std::vector<Vec3> normals;    //!< 空のこともある（細分割の直後など）
        std::vector<Vec2> uvs;        //!< 空のこともある（UV 展開前）
        std::vector<u32>  indices;

        //! 頂点を追加します。
        //! @param  [in] position 頂点位置
        //! @return 追加した頂点の番号
        u32 AddVertex(const Vec3& position);

        //! 三角形を追加します。
        //! @param [in] a 1つ目の頂点番号
        //! @param [in] b 2つ目の頂点番号
        //! @param [in] c 3つ目の頂点番号
        void AddTriangle(u32 a, u32 b, u32 c);

        //! 頂点数を返します。
        //! @return 頂点数
        u32 GetVertexCount() const { return static_cast<u32>(positions.size()); }

        //! 三角形数を返します。
        //! @return 三角形数
        u32 GetTriangleCount() const { return static_cast<u32>(indices.size() / 3); }

        //! バウンディングボックスを求めます。空なら両端が 0 になります。
        //! @param [out] outMin 最小側
        //! @param [out] outMax 最大側
        void ComputeBounds(Vec3& outMin, Vec3& outMax) const;

        //! 最も長いエッジの長さを求めます。細分割の停止判定に使います。
        //! @return 最長エッジ長
        float ComputeMaxEdgeLength() const;

        //! 中身を空にします。確保済み領域は手放しません。
        void Clear();

        //! normals と uvs を捨てます。位相を変える操作の前に呼びます。
        void DiscardAttributes();

        //------------------------------------------------------------------
        //! どの三角形からも参照されていない頂点を取り除きます。
        //!
        //! 半空間クリップは平面の外側の三角形を捨てますが、その頂点は
        //! positions に残ったままです。残しても描画結果は変わらないので
        //! 長く放置していましたが、次の 2 つで実際に害が出ます。
        //!
        //!   - xatlas はどのチャートにも属さない頂点として返してくる。
        //!     その UV は (0,0) なので、通すとアトラスの原点へ向かう
        //!     巨大な三角形ができてベイクが壊れる
        //!   - 頂点バッファとベイクの頂点数が実際より多く見える
        //!
        //! 位置・法線・UV を同じ順で詰め直し、indices を振り直します。
        //!
        //! @return 取り除いた頂点数
        //------------------------------------------------------------------
        u32 RemoveUnusedVertices();

        //------------------------------------------------------------------
        //! 近すぎる頂点を溶接し、潰れた三角形を取り除きます。
        //!
        //! 半空間クリップは、交点がたまたま既存の頂点のすぐ近くに落ちると
        //! 「底辺が辺の長さ・高さが数マイクロメートル」という針のような
        //! 三角形を残します。面積は 1e-7 を下回ることがあり、xatlas は
        //! それを無効な面として弾いてしまいます（弾かれた面の UV は (0,0)
        //! のまま返るので、通すとアトラスの原点へ伸びる巨大な三角形ができる）。
        //!
        //! クリップの側で交点を端点へ強く寄せて防ごうとすると、切り口の
        //! 多角形が線分へ潰れて断面に穴が開きます。**位相を組み終わった後に
        //! 辺を縮める**のが正しい順序で、それがこの関数です。
        //!
        //! 辺を縮めるので位相は保たれます。溶接した辺に接していた 2 枚は
        //! 同じ頂点を 2 つ持つ三角形になるので取り除き、残りの三角形は
        //! 代表の頂点を指すよう差し替えます。閉じたメッシュは閉じたまま
        //! になります（退化した三角形を溶接せずに捨てると、そこに
        //! 幅 0 の穴が開く。必ず溶接と同時に行うこと）。
        //!
        //! @param  [in] epsilon この距離より近い頂点を同一視する
        //! @return 取り除いた頂点数
        //------------------------------------------------------------------
        u32 WeldCloseVertices(float epsilon);

        //------------------------------------------------------------------
        //! 面積の小さすぎる三角形を、その最短辺を縮めて取り除きます。
        //!
        //! WeldCloseVertices では落としきれない分を掃除するためのものです。
        //! 溶接は「頂点どうしが近い」ものしか畳めませんが、実際に残るのは
        //! 「3 頂点が互いに 2e-4 ほど離れた極小の三角形」で、溶接の幅を
        //! そこまで広げると本来の形まで削れてしまいます。面積で選んで
        //! 最短辺だけを縮めれば、動かす距離はその辺の長さで済みます。
        //!
        //! maxEdgeLength は保険です。3 頂点が一直線に並んだだけの
        //! 「長くて細い」三角形は、辺を縮めると形が目に見えて変わるので
        //! 触りません（残ってしまうので、検証で気付けるようにしてある）。
        //!
        //! 1 回の縮めで隣の三角形が新たに潰れることがあるので、
        //! 変化が無くなるまで最大 maxPasses 回繰り返します。
        //!
        //! @param  [in] minArea       この面積以下の三角形を対象にする
        //! @param  [in] maxEdgeLength これより長い辺は縮めない
        //! @param  [in] maxPasses     繰り返しの上限
        //! @return 縮めた辺の数
        //------------------------------------------------------------------
        u32 CollapseSliverTriangles(float minArea, float maxEdgeLength, int maxPasses);
    };

}    // namespace RockCore
