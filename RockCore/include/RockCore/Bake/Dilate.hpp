//----------------------------------------------------------------------------
//! @file   Dilate.hpp
//! @brief  被覆マスクに沿った画像の膨張
//! @detail チャートの外側へ色をにじませます。これをしないとミップの粗い
//!         レベルでチャート間の未被覆テクセルが混ざり、境界に線が出ます。
//!
//!         全マップ（Normal / Albedo / MR / AO）へ同じマスクを使います。
//----------------------------------------------------------------------------
#pragma once
#include <RockCore/Bake/ImageBuffer.hpp>

#include <vector>

// 名前空間 RockCore
namespace RockCore {

    //------------------------------------------------------------------------
    //! 被覆マスクの外側へ色を膨張させます。
    //!
    //! 1パスで 1 テクセルぶん広がります。マスクはパスごとにまとめて更新する
    //! ので、走査順に結果が依存しません（決定論のため）。
    //!
    //! @param [in,out] image    対象の画像
    //! @param [in]     coverage 被覆マスク（0 = 未被覆）。画像と同じ大きさ
    //! @param [in]     passes   膨張のパス数
    //------------------------------------------------------------------------
    void DilateImage(ImageBuffer& image, const std::vector<u8>& coverage, int passes);

}    // namespace RockCore
